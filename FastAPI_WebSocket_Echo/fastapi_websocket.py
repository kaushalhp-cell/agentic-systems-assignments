import asyncio
import websockets

async def test():
    """
    Simple Python WebSocket client to test the echo server
    """
    async with websockets.connect("ws://localhost:8000/ws") as websocket:
        # Send message
        await websocket.send("Hello Server")

        # Receive response
        response = await websocket.recv()
        print(response)

# Run the test
asyncio.run(test())